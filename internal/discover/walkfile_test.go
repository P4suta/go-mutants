func walkOne(t *testing.T, d *discovery, name, src string) error {
	t.Helper()

	loaded, pkg := loadedPackage(t, name, src)
	return d.file(loaded, pkg, pkg.Syntax[0])
}

type parsed struct {
	fset *token.FileSet
	file *ast.File
	info *types.Info
	pkg  *types.Package
}

func parsedAt(t *testing.T, name, src string) parsed {
	t.Helper()

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, name, src, parser.ParseComments)
	if err != nil {
		t.Fatalf("parsing %s:\n%s\n%v", name, src, err)
	}
	info := &types.Info{
		Types:      map[ast.Expr]types.TypeAndValue{},
		Defs:       map[*ast.Ident]types.Object{},
		Uses:       map[*ast.Ident]types.Object{},
		Selections: map[*ast.SelectorExpr]*types.Selection{},
	}
	conf := types.Config{Importer: importer.ForCompiler(fset, "source", nil)}
	pkg, err := conf.Check("example.com/m/pkg", fset, []*ast.File{file}, info)
	if err != nil {
		t.Fatalf("the fixture does not type-check:\n%s\n%v", src, err)
	}
	return parsed{fset: fset, file: file, info: info, pkg: pkg}
}

func loadedPackage(t *testing.T, name, src string) (*loadResult, *packages.Package) {
	t.Helper()

	p := parsedAt(t, name, src)
	return &loadResult{fset: p.fset}, &packages.Package{
		PkgPath:   "example.com/m/pkg",
		Syntax:    []*ast.File{p.file},
		TypesInfo: p.info,
		Types:     p.pkg,
	}
}

const walkFixture = "package pkg\n\n// Widest returns the larger of two numbers.\n" +
	"func Widest(a, b int) int {\n\tif a <= b {\n\t\treturn b\n\t}\n\treturn a\n}\n"

func newWalkDiscovery(t *testing.T, root string) *discovery {
	t.Helper()

	selected, err := newMatchers(SupportedRules())
	if err != nil {
		t.Fatalf("building the matchers: %v", err)
	}
	return &discovery{
		root:     root,
		matchers: selected,
		skips:    map[skipKey]int{},
		seen:     map[string]bool{},
		digests:  map[string]string{},
	}
}

func TestWhichOfAPackagesFilesAreWalked(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	at := func(parts ...string) string { return filepath.Join(append([]string{root}, parts...)...) }

	for _, c := range []struct {
		name   string
		file   string
		src    string
		walked bool
		reason SkipReason
	}{
		{name: "a file of the module", file: at("pkg", "widest.go"), src: walkFixture, walked: true},
		{name: "a test file", file: at("pkg", "widest_test.go"), src: walkFixture},
		{
			name: "a file outside the module root",
			file: filepath.Join(filepath.Dir(root), "elsewhere", "widest.go"),
			src:  walkFixture,
		},
		{
			name:   "a generated file",
			file:   at("pkg", "generated.go"),
			src:    "// Code generated by a tool. DO NOT EDIT.\n\n" + walkFixture,
			reason: SkipGenerated,
		},
	} {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()

			d := newWalkDiscovery(t, root)
			if err := writeSource(t, c.file, c.src); err != nil {
				t.Fatalf("writing the source: %v", err)
			}
			if err := walkOne(t, d, c.file, c.src); err != nil {
				t.Fatalf("walking %s: %v", c.file, err)
			}
			if got := len(d.candidates) > 0; got != c.walked {
				t.Errorf("the file produced candidates = %v, want %v", got, c.walked)
			}
			var recorded SkipReason
			for key := range d.skips {
				recorded = key.reason
			}
			if recorded != c.reason {
				t.Errorf("the file was recorded as %q, want %q", recorded, c.reason)
			}
		})
	}
}

func writeSource(t *testing.T, path, src string) error {
	t.Helper()

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(src), 0o644)
}

func TestAFileWalkedTwiceIsWalkedOnce(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	path := filepath.Join(root, "pkg", "widest.go")
	if err := writeSource(t, path, walkFixture); err != nil {
		t.Fatalf("writing the source: %v", err)
	}

	d := newWalkDiscovery(t, root)
	if err := walkOne(t, d, path, walkFixture); err != nil {
		t.Fatalf("the first walk: %v", err)
	}
	first := len(d.candidates)
	if first == 0 {
		t.Fatal("the fixture produced no candidates")
	}
	if err := walkOne(t, d, path, walkFixture); err != nil {
		t.Fatalf("the second walk: %v", err)
	}
	if len(d.candidates) != first {
		t.Errorf("a second walk of one file emitted %d more candidates", len(d.candidates)-first)
	}
}

func TestAFileTheWalkCannotReadStopsTheRun(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	absent := filepath.Join(root, "pkg", "gone.go")

	d := newWalkDiscovery(t, root)
	err := walkOne(t, d, absent, walkFixture)
	if err == nil {
		t.Fatal("a walk over a file that is not there succeeded, want a refusal")
	}
	if code := CodeOf(err); code != CodeFileUnreadable {
		t.Fatalf("CodeOf(%v) = %q, want %q", err, code, CodeFileUnreadable)
	}
	if !strings.Contains(err.Error(), "pkg/gone.go") {
		t.Errorf("the refusal %q does not name the file, module-relative", err)
	}
	if len(d.candidates) != 0 {
		t.Errorf("the refusal left %d candidates behind", len(d.candidates))
	}
}

func TestASelectionThatExcludesAFileRecordsWhy(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	path := filepath.Join(root, "pkg", "widest.go")
	if err := writeSource(t, path, walkFixture); err != nil {
		t.Fatalf("writing the source: %v", err)
	}

	d := newWalkDiscovery(t, root)
	pattern, err := glob.Compile("pkg/*.go")
	if err != nil {
		t.Fatalf("compiling the exclusion: %v", err)
	}
	d.exclude = []glob.Pattern{pattern}
	if err := walkOne(t, d, path, walkFixture); err != nil {
		t.Fatalf("walking: %v", err)
	}
	if len(d.candidates) != 0 {
		t.Errorf("an excluded file produced %d candidates", len(d.candidates))
	}
	if got := d.skips[skipKey{path: "pkg/widest.go", reason: SkipExcluded}]; got != 1 {
		t.Errorf("the file was recorded %d times as excluded, want once", got)
	}
}

func TestAWalkWithNoRulesOpensNothing(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	path := filepath.Join(root, "pkg", "widest.go")
	if err := writeSource(t, path, walkFixture); err != nil {
		t.Fatalf("writing the source: %v", err)
	}

	d := &discovery{
		root:    root,
		skips:   map[skipKey]int{},
		seen:    map[string]bool{},
		digests: map[string]string{},
	}
	if err := walkOne(t, d, path, walkFixture); err != nil {
		t.Fatalf("walking: %v", err)
	}
	if len(d.digests) != 0 {
		t.Errorf("a walk with no rule selected recorded the digests %v, want none", d.digests)
	}
	if len(d.candidates) != 0 || len(d.skips) != 0 {
		t.Errorf("a walk with no rule selected produced %d candidates and %d skips",
			len(d.candidates), len(d.skips))
	}
}

func TestASnapshotRootIsADirectoryThisProcessCanSee(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	file := filepath.Join(root, "go.mod")
	if err := os.WriteFile(file, []byte("module example.com/m\n\ngo 1.26\n"), 0o644); err != nil {
		t.Fatalf("writing go.mod: %v", err)
	}

	if got, err := resolveRoot(root); err != nil || got != root {
		t.Errorf("resolveRoot(%q) = (%q, %v), want the directory itself", root, got, err)
	}
	if got, err := resolveRoot("."); err != nil || !filepath.IsAbs(got) {
		t.Errorf("resolveRoot(\".\") = (%q, %v), want an absolute path", got, err)
	}

	for _, c := range []struct {
		name string
		root string
		says string
	}{
		{name: "nothing at all", root: "", says: "no snapshot root was given"},
		{name: "whitespace", root: "  \t ", says: "no snapshot root was given"},
		{name: "a path that is not there", root: filepath.Join(root, "absent"), says: "cannot read"},
		{name: "a file", root: file, says: "is not a directory"},
	} {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()

			got, err := resolveRoot(c.root)
			if err == nil {
				t.Fatalf("resolveRoot(%q) = %q, want a refusal", c.root, got)
			}
			if code := CodeOf(err); code != CodeSnapshotRoot {
				t.Fatalf("CodeOf(%v) = %q, want %q", err, code, CodeSnapshotRoot)
			}
			if !strings.Contains(err.Error(), c.says) {
				t.Errorf("the refusal %q does not say %q", err, c.says)
			}
		})
	}
}

func TestADiscoveryStopsWhenItsContextDoes(t *testing.T) {
	t.Parallel()

	ctx, cancel := context.WithCancel(t.Context())
	cancel()

	d := newWalkDiscovery(t, t.TempDir())
	loaded := &loadResult{fset: token.NewFileSet(), packages: []*packages.Package{{PkgPath: "example.com/m/pkg"}}}
	err := d.run(ctx, loaded)
	if err == nil {
		t.Fatal("a discovery under a cancelled context succeeded, want a refusal")
	}
	if code := CodeOf(err); code != CodeLoadFailed {
		t.Fatalf("CodeOf(%v) = %q, want %q", err, code, CodeLoadFailed)
	}
	if !strings.Contains(err.Error(), "cancelled") {
		t.Errorf("the refusal %q does not say the run was cancelled", err)
	}

	if err := d.run(t.Context(), loaded); err != nil {
		t.Errorf("a discovery under a live context: %v", err)
	}
}

func TestASuppressionCountedZeroTimesIsNotCounted(t *testing.T) {
	t.Parallel()

	d := newWalkDiscovery(t, t.TempDir())
	d.record("pkg/a.go", SkipGenerated, 0)
	d.record("pkg/a.go", SkipGenerated, -1)
	if len(d.skips) != 0 {
		t.Errorf("a suppression counted zero times recorded %v", d.skips)
	}
	d.record("pkg/a.go", SkipGenerated, 2)
	if got := d.skips[skipKey{path: "pkg/a.go", reason: SkipGenerated}]; got != 2 {
		t.Errorf("the count is %d, want 2", got)
	}
}
